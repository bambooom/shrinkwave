export const messages: Record<Locale, Messages> = { "zh-CN": zhCN, "zh-TW": zhTW, en, ja };

const STORAGE_KEY = "pixel-tools.locale";

export function detectLocale(): Locale {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved && saved in messages) return saved as Locale;

  for (const language of navigator.languages) {
    const tag = language.toLowerCase();
    if (tag.startsWith("zh")) return /hant|tw|hk|mo/.test(tag) ? "zh-TW" : "zh-CN";
    if (tag.startsWith("ja")) return "ja";
    if (tag.startsWith("en")) return "en";
  }
  return "en";
}

export function saveLocale(locale: Locale) {
  localStorage.setItem(STORAGE_KEY, locale);
}
